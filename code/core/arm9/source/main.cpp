static bool shouldMountDsiSd(int argc, char* argv[])
{
    if (!Environment::IsDsiMode())
        return false;

    if (argc == 0)
        return true;

    if (argv[0][0] == 'f' && argv[0][1] == 'a' && argv[0][2] == 't' && argv[0][3] == ':')
        return false;

    return true;
}

/// @brief Keeps the boot diagnostics badge on screen long enough to actually read
///        on real hardware (~60 frames / ~1 s), or until A or Start is pressed
///        to skip straight to the game. Polls VCOUNT so it works after the
///        splash VBlank handler has been stopped.
static void holdBootBadge()
{
    for (u32 frames = 0; frames < 60; frames++)
    {
        // GBA/DS REG_KEYINPUT is active LOW: A (bit 0) or Start (bit 3).
        if ((*(volatile u16*)0x04000130 & 0x0009) == 0)
            break;
        while (*(volatile u16*)0x04000006 < 160);  // wait for vblank start
        while (*(volatile u16*)0x04000006 >= 160); // wait for vblank end
    }
}

static void applyGameJitPatches()
{
    gLogger->Log(LogLevel::Debug, "Applying game JIT patches...\n");

    const auto& runSettings = gAppSettingsService.GetAppSettings().runSettings;
    for (u32 i = 0; i < runSettings.jitPatchAddressCount; ++i)
    {
        u32 jitPatchAddress = runSettings.jitPatchAddresses[i];
        if (jitPatchAddress >= 0x08000000u && jitPatchAddress < 0x0A000000u)
        {
            gLogger->Log(LogLevel::Debug, "0x%08X\n", jitPatchAddress);
            // Apply to the sd cache block (which serves both the linear window
            // and the paged high rom) and remember the result so the patch also
            // survives eviction of the containing block.
            u32* patchPtr = static_cast<u32*>(sdc_loadRomBlockForPatching(jitPatchAddress));
            jit_processArmInstruction(patchPtr);
            sdc_patchRom(jitPatchAddress, *patchPtr, 4);
        }
    }
}

static void setupJit()
{
    jit_init();

    const auto& runSettings = gAppSettingsService.GetAppSettings().runSettings;
    if (runSettings.enableJit)
    {
        if (runSettings.jitPatchAddresses && runSettings.jitPatchAddressCount > 0)
        {
            // manual jit patches
            applyGameJitPatches();
            jit_disable();
        }
        else
        {
            // jit enabled
            applyBiosJitPatches();
        }
    }
    else
    {
        // jit disabled
        jit_disable();
    }
}

