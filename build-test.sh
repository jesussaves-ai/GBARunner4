#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Build a TEST variant of GBARunner with a GBA ROM embedded in the ARM9 core.
#
# The test build uses NO filesystem at all: at boot it copies the embedded ROM
# straight into the GBA linear window (0x02200000) instead of going through
# DLDI/SD/SdCache. Test ROMs are far smaller than the 2 MB linear window, so
# this is complete. It is meant for exercising the hypervisor headlessly and on
# hardware, and is kept entirely separate from the normal build.
#
# For >2 MB ROMs (real games) the normal build + real storage is used instead.
#
# Usage:
#   ./build-test.sh <rom.gba> [out.nds]      # default out: dist-test/GBARunner3-test.nds
# ---------------------------------------------------------------------------
set -u
set -o pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROM="${1:-}"
OUT="${2:-$ROOT/dist-test/GBARunner3-test.nds}"

if [ -z "$ROM" ] || [ ! -f "$ROM" ]; then
    echo "usage: $0 <rom.gba> [out.nds]" >&2
    exit 2
fi

SIZE=$(stat -c%s "$ROM")
if [ "$SIZE" -gt $((2 * 1024 * 1024)) ]; then
    echo "❌ ROM is $SIZE bytes (> 2 MB): the test build only serves the linear window." >&2
    exit 2
fi

HDR="$ROOT/code/core/arm9/source/EmbeddedRom.h"
BIOS="${GBA_BIOS:-/mnt/storage/BIOS/gba_bios.bin}"
if [ ! -f "$BIOS" ]; then
    echo "❌ GBA BIOS not found (set GBA_BIOS=/path/to/gba_bios.bin)" >&2
    exit 2
fi
BIOS_SIZE=$(stat -c%s "$BIOS")
if [ "$BIOS_SIZE" -ne 16384 ]; then
    echo "❌ GBA BIOS must be 16384 bytes (got $BIOS_SIZE)" >&2
    exit 2
fi

python3 - "$ROM" "$BIOS" "$HDR" <<'PY'
import sys
rom = open(sys.argv[1], 'rb').read()
bios = open(sys.argv[2], 'rb').read()
def emit(o, name, data):
    o.write("static const unsigned char %s[] = {\n" % name)
    for i in range(0, len(data), 16):
        o.write("  " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    o.write("};\n")
with open(sys.argv[3], 'w') as o:
    o.write("// Auto-generated by build-test.sh -- do not commit.\n#pragma once\n")
    emit(o, "kEmbeddedRom", rom)
    o.write("static const unsigned int kEmbeddedRomSize = %d;\n" % len(rom))
    emit(o, "kEmbeddedBios", bios)
    o.write("static const unsigned int kEmbeddedBiosSize = %d;\n" % len(bios))
PY
echo "embedded $(basename "$ROM") ($SIZE bytes) + BIOS ($BIOS_SIZE bytes)"

mkdir -p "$(dirname "$OUT")"
# By default the test build also writes /_gba/result.bmp (the captured DS
# screen) to the SD. Set GBAR3_SCREENSHOT=0 to build without it.
DEFS="GBAR3_EMBED_ROM=1"
if [ "${GBAR3_SCREENSHOT:-1}" != "0" ]; then
    DEFS="$DEFS GBAR3_SCREENSHOT=1"
fi
# libtwl must be built before the bootstrap links; a plain `make -C bootstrap`
# only works when a previous full build already produced libtwl9/libtwl7.
# The core object trees are removed explicitly: the test build compiles the
# same sources with different -D flags and make does not track flag changes.
docker run --rm -v "$ROOT":/gba devkitpro/devkitarm:20230928 bash -c \
    "cd /gba/code && make -C libs/libtwl >/dev/null 2>&1 && \
     rm -rf core/arm9/build core/arm7/build && \
     cd bootstrap && make clean >/dev/null 2>&1 && make $DEFS 2>&1 | tail -3" || {
    echo "❌ test build failed" >&2
    exit 1
}

if [ ! -f "$ROOT/code/bootstrap/GBARunner3.nds" ]; then
    echo "❌ test build produced no .nds" >&2
    exit 1
fi

cp -f "$ROOT/code/bootstrap/GBARunner3.nds" "$OUT"
echo "✅ test build: $OUT"
